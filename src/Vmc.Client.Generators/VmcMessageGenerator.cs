using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Globalization;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace Vmc.Client.Generators;

/// <summary>
/// Turns <c>vmc-protocol.txt</c> (an additional file listing every VMC message) into one record per message with
/// its OSC encoding and decoding, and a dispatch table from address to message.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class VmcMessageGenerator : IIncrementalGenerator
{
    private static readonly DiagnosticDescriptor _badLine = new(
        "VMCGEN001",
        "Unreadable protocol line",
        "Line {0} of vmc-protocol.txt is not 'name | address | direction | since | arguments [| optional]': {1}",
        "Vmc.Client.Generators",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true
    );

    /// <inheritdoc/>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValuesProvider<AdditionalText> tables = context.AdditionalTextsProvider.Where(
            static file =>
                file.Path.EndsWith("vmc-protocol.txt", StringComparison.OrdinalIgnoreCase)
        );
        context.RegisterSourceOutput(
            tables.Select(
                static (file, ct) => (file.Path, Text: file.GetText(ct)?.ToString() ?? string.Empty)
            ),
            Emit
        );
    }

    private static void Emit(SourceProductionContext context, (string Path, string Text) table)
    {
        List<Message> messages = [];
        string[] lines = table.Text.Split('\n');
        for (int index = 0; index < lines.Length; index++)
        {
            string line = lines[index].Trim();
            if (line.Length == 0 || line[0] == '#')
            {
                continue;
            }

            if (Message.TryParse(line) is { } message)
            {
                messages.Add(message);
            }
            else
            {
                context.ReportDiagnostic(
                    Diagnostic.Create(_badLine, Location.None, index + 1, line)
                );
            }
        }

        foreach (Message message in messages)
        {
            context.AddSource(
                $"{message.Name}.g.cs",
                SourceText.From(message.Render(), Encoding.UTF8)
            );
        }

        context.AddSource(
            "VmcMessages.g.cs",
            SourceText.From(RenderDispatch(messages), Encoding.UTF8)
        );
    }

    private static string RenderDispatch(List<Message> messages)
    {
        StringBuilder s = new();
        s.AppendLine("// <auto-generated/>");
        s.AppendLine("#nullable enable");
        s.AppendLine("namespace Vmc.Client;");
        s.AppendLine();
        s.AppendLine("/// <summary>Every message the VMC protocol defines, by address.</summary>");
        s.AppendLine("public static partial class VmcMessages");
        s.AppendLine("{");
        s.AppendLine(
            "    /// <summary>Reads an OSC message as the VMC message its address names.</summary>"
        );
        s.AppendLine("    /// <param name=\"message\">The OSC message.</param>");
        s.AppendLine(
            "    /// <param name=\"result\">The VMC message, when the address is known and the arguments fit.</param>"
        );
        s.AppendLine(
            "    /// <returns>Whether it was read. Unknown addresses and missing or mistyped arguments are not, as the protocol asks receivers to ignore them.</returns>"
        );
        s.AppendLine(
            "    public static bool TryRead(OscMessage message, [global::System.Diagnostics.CodeAnalysis.NotNullWhen(true)] out IVmcMessage? result)"
        );
        s.AppendLine("    {");
        s.AppendLine("        switch (message.Address)");
        s.AppendLine("        {");
        foreach (Message message in messages)
        {
            s.AppendLine($"            case {message.Name}.AddressPattern:");
            s.AppendLine(
                $"                if ({message.Name}.TryRead(message, out {message.Name}? {Camel(message.Name)}))"
            );
            s.AppendLine("                {");
            s.AppendLine($"                    result = {Camel(message.Name)};");
            s.AppendLine("                    return true;");
            s.AppendLine("                }");
            s.AppendLine("                break;");
        }

        s.AppendLine("        }");
        s.AppendLine();
        s.AppendLine("        result = null;");
        s.AppendLine("        return false;");
        s.AppendLine("    }");
        s.AppendLine("}");
        return s.ToString();
    }

    private static string Camel(string name) =>
        "@" + char.ToLowerInvariant(name[0]) + name.Substring(1);

    private sealed record Argument(char Type, string Name, string? Since)
    {
        public string ClrType =>
            Type switch
            {
                's' => "string",
                'i' => "int",
                _ => "float",
            };

        public string Accessor =>
            Type switch
            {
                's' => "String",
                'i' => "Int32",
                _ => "Float32",
            };
    }

    private static readonly char[] _space = [' '];

    private sealed record Message(
        string Name,
        string Address,
        string Direction,
        string Since,
        ImmutableArray<Argument> Required,
        ImmutableArray<Argument> Optional
    )
    {
        public static Message? TryParse(string line)
        {
            string[] parts = line.Split('|').Select(static p => p.Trim()).ToArray();
            if (
                parts.Length < 4
                || parts[0].Length == 0
                || !parts[1].StartsWith("/", StringComparison.Ordinal)
            )
            {
                return null;
            }

            ImmutableArray<Argument>? required = Arguments(
                parts.Length > 4 ? parts[4] : string.Empty,
                optional: false
            );
            ImmutableArray<Argument>? optional = Arguments(
                parts.Length > 5 ? parts[5] : string.Empty,
                optional: true
            );
            return required is null || optional is null
                ? null
                : new Message(
                    parts[0],
                    parts[1],
                    parts[2],
                    parts[3],
                    required.Value,
                    optional.Value
                );
        }

        private static ImmutableArray<Argument>? Arguments(string text, bool optional)
        {
            ImmutableArray<Argument>.Builder arguments = ImmutableArray.CreateBuilder<Argument>();
            foreach (string token in text.Split(_space, StringSplitOptions.RemoveEmptyEntries))
            {
                string[] typeAndName = token.Split(':');
                if (
                    typeAndName.Length != 2
                    || typeAndName[0].Length != 1
                    || "sif".IndexOf(typeAndName[0][0]) < 0
                )
                {
                    return null;
                }

                string[] nameAndSince = typeAndName[1].Split('@');
                if (optional != (nameAndSince.Length == 2))
                {
                    return null;
                }

                arguments.Add(
                    new Argument(
                        typeAndName[0][0],
                        nameAndSince[0],
                        optional ? nameAndSince[1] : null
                    )
                );
            }

            return arguments.ToImmutable();
        }

        public string Render()
        {
            StringBuilder s = new();
            string parameters = string.Join(
                ", ",
                Required
                    .Select(static a => $"{a.ClrType} {a.Name}")
                    .Concat(Optional.Select(static a => $"{a.ClrType}? {a.Name} = null"))
            );
            s.AppendLine("// <auto-generated/>");
            s.AppendLine("#nullable enable");
            s.AppendLine("namespace Vmc.Client;");
            s.AppendLine();
            s.AppendLine(
                $"/// <summary><c>{Address}</c> ({Sentence(Direction)}, since protocol {Since}).</summary>"
            );
            foreach (Argument a in Required)
            {
                s.AppendLine($"/// <param name=\"{a.Name}\">The <c>{a.Name}</c> argument.</param>");
            }

            foreach (Argument a in Optional)
            {
                s.AppendLine(
                    $"/// <param name=\"{a.Name}\">The <c>{a.Name}</c> argument, added in protocol {a.Since}; null when the sender is older.</param>"
                );
            }

            s.AppendLine($"public sealed partial record {Name}({parameters}) : IVmcMessage");
            s.AppendLine("{");
            s.AppendLine("    /// <summary>The OSC address.</summary>");
            s.AppendLine($"    public const string AddressPattern = \"{Address}\";");
            s.AppendLine();
            s.AppendLine("    /// <inheritdoc/>");
            s.AppendLine("    public string Address => AddressPattern;");
            s.AppendLine();
            s.AppendLine("    /// <inheritdoc/>");
            s.AppendLine($"    public VmcDirection Direction => VmcDirection.{Direction};");
            s.AppendLine();
            s.AppendLine("    /// <inheritdoc/>");
            s.AppendLine("    public OscMessage ToOsc()");
            s.AppendLine("    {");
            s.AppendLine(
                $"        var arguments = new global::System.Collections.Generic.List<OscArgument>({Required.Length + Optional.Length});"
            );
            foreach (Argument a in Required)
            {
                s.AppendLine($"        arguments.Add(OscArgument.From{a.Accessor}({a.Name}));");
            }

            // Trailing arguments go out in order until the first missing one, which is how an older sender looks.
            foreach (Argument a in Optional)
            {
                s.AppendLine(
                    $"        if ({a.Name} is not {{ }} {Camel(a.Name)}) {{ return new OscMessage(AddressPattern, [.. arguments]); }}"
                );
                s.AppendLine(
                    $"        arguments.Add(OscArgument.From{a.Accessor}({Camel(a.Name)}));"
                );
            }

            s.AppendLine("        return new OscMessage(AddressPattern, [.. arguments]);");
            s.AppendLine("    }");
            s.AppendLine();
            s.AppendLine(
                "    /// <summary>Reads the message's arguments; surplus arguments are ignored, as the protocol asks.</summary>"
            );
            s.AppendLine(
                "    /// <param name=\"message\">An OSC message at <see cref=\"AddressPattern\"/>.</param>"
            );
            s.AppendLine(
                "    /// <param name=\"result\">The message, when the arguments fit.</param>"
            );
            s.AppendLine("    /// <returns>Whether they did.</returns>");
            s.AppendLine(
                $"    public static bool TryRead(OscMessage message, [global::System.Diagnostics.CodeAnalysis.NotNullWhen(true)] out {Name}? result)"
            );
            s.AppendLine("    {");
            s.AppendLine("        result = null;");
            s.AppendLine("        var a = message.Arguments;");
            s.AppendLine($"        if (a.Length < {Required.Length}) {{ return false; }}");
            for (int i = 0; i < Required.Length; i++)
            {
                s.AppendLine(
                    $"        if (!a[{i}].TryGet{Required[i].Accessor}(out {Required[i].ClrType} v{i})) {{ return false; }}"
                );
            }

            for (int i = 0; i < Optional.Length; i++)
            {
                int at = Required.Length + i;
                s.AppendLine(
                    $"        {Optional[i].ClrType}? o{i} = a.Length > {at} && a[{at}].TryGet{Optional[i].Accessor}(out {Optional[i].ClrType} t{i}) ? t{i} : null;"
                );
            }

            string values = string.Join(
                ", ",
                Enumerable
                    .Range(0, Required.Length)
                    .Select(static i => $"v{i}")
                    .Concat(Enumerable.Range(0, Optional.Length).Select(static i => $"o{i}"))
            );
            s.AppendLine($"        result = new {Name}({values});");
            s.AppendLine("        return true;");
            s.AppendLine("    }");
            s.AppendLine("}");
            return s.ToString();
        }

        private static string Sentence(string direction) =>
            direction switch
            {
                "ToMarionette" => "performer to marionette",
                "ToPerformer" => "marionette or assistant to performer",
                _ => "either direction",
            };
    }
}
